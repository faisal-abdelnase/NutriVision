import 'package:flutter/material.dart';
import 'package:nutri_vision/core/utils/validators.dart';
import 'package:nutri_vision/features/recipes/domain/entities/grocery_item.dart';

/// Bottom sheet (mobile) / dialog (tablet+). Pops with a [GroceryItem].
class AddGroceryItemSheet extends StatefulWidget {
  const AddGroceryItemSheet({super.key, required this.userId});
  final String userId;

  @override
  State<AddGroceryItemSheet> createState() => _AddGroceryItemSheetState();
}

class _AddGroceryItemSheetState extends State<AddGroceryItemSheet> {
  static const _units = ['pcs', 'g', 'kg', 'ml', 'l', 'cup', 'tbsp', 'tsp'];

  final _formKey = GlobalKey<FormState>();
  final _name = TextEditingController();
  final _quantity = TextEditingController(text: '1');
  String _unit = _units.first;

  @override
  void dispose() {
    _name.dispose();
    _quantity.dispose();
    super.dispose();
  }

  void _submit() {
    if (!_formKey.currentState!.validate()) return;
    final quantity = double.parse(_quantity.text.trim().replaceAll(',', '.'));
    Navigator.pop(
      context,
      GroceryItem(
        id: '', // generated by the local data source
        userId: widget.userId,
        name: _name.text.trim(),
        quantity: quantity,
        unit: _unit,
        createdAt: DateTime.now(),
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    return Padding(
      padding: EdgeInsets.fromLTRB(
        20,
        20,
        20,
        20 + MediaQuery.viewInsetsOf(context).bottom,
      ),
      child: Form(
        key: _formKey,
        child: Column(
          mainAxisSize: MainAxisSize.min,
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: [
            Text('Add item', style: Theme.of(context).textTheme.headlineSmall),
            const SizedBox(height: 16),
            TextFormField(
              controller: _name,
              autofocus: true,
              textCapitalization: TextCapitalization.sentences,
              decoration: const InputDecoration(labelText: 'Item name'),
              validator: (v) => Validators.required(v),
            ),
            const SizedBox(height: 12),
            Row(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Expanded(
                  child: TextFormField(
                    controller: _quantity,
                    keyboardType:
                        const TextInputType.numberWithOptions(decimal: true),
                    decoration: const InputDecoration(labelText: 'Quantity'),
                    validator: (v) {
                      final n = double.tryParse((v ?? '').trim().replaceAll(',', '.'));
                      return (n == null || n <= 0) ? 'Enter a valid number' : null;
                    },
                  ),
                ),
                const SizedBox(width: 12),
                Expanded(
                  child: DropdownButtonFormField<String>(
                    initialValue: _unit,
                    decoration: const InputDecoration(labelText: 'Unit'),
                    items: [
                      for (final u in _units)
                        DropdownMenuItem(value: u, child: Text(u)),
                    ],
                    onChanged: (v) => setState(() => _unit = v ?? _unit),
                  ),
                ),
              ],
            ),
            const SizedBox(height: 20),
            ElevatedButton(onPressed: _submit, child: const Text('Add')),
          ],
        ),
      ),
    );
  }
}
